#!/usr/bin/env python3
"""Generate native firmware preset tables from patches/library JSON catalogs."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBRARY = ROOT / "patches" / "library"
OUTPUT = ROOT / "app" / "fm1lab_engine_presets.generated.h"
ENGINES = ("wavetable", "psg", "subtractive")
FIELDS = ("waveform", "secondary_waveform", "duty", "noise_mix", "osc_mix",
          "detune", "cutoff", "attack", "sustain", "release")
PREFIX = {"wavetable": "WT-", "psg": "PSG-", "subtractive": "SUB-"}

def load_catalogs():
    catalogs = {engine: [] for engine in ENGINES}
    seen = set()
    for path in sorted(LIBRARY.glob("*/*/patches.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        engine = data.get("engine")
        if engine not in catalogs:
            continue
        for patch in data.get("patches", []):
            patch_id, name, params = patch.get("patch_id"), patch.get("name"), patch.get("parameters")
            if not isinstance(patch_id, str) or not patch_id.startswith(PREFIX[engine]):
                raise SystemExit(f"{path}: invalid {engine} patch_id {patch_id!r}")
            if patch_id in seen:
                raise SystemExit(f"duplicate engine patch ID: {patch_id}")
            seen.add(patch_id)
            if not isinstance(name, str) or not name or not isinstance(params, dict):
                raise SystemExit(f"{path}: {patch_id} needs name and parameters")
            if set(params) != set(FIELDS):
                raise SystemExit(f"{path}: {patch_id} parameter fields must be exactly {FIELDS}")
            values = []
            for field in FIELDS:
                value = params[field]
                if not isinstance(value, int) or not 0 <= value <= 100:
                    raise SystemExit(f"{path}: {patch_id}.{field} must be an integer 0..100")
                values.append(value)
            catalogs[engine].append((patch_id, name, values))
    for engine, entries in catalogs.items():
        entries.sort(key=lambda item: item[0])
        if len(entries) != 4:
            raise SystemExit(f"{engine}: expected exactly 4 native presets, found {len(entries)}")
    return catalogs

def render(catalogs):
    lines = [
        "/* Generated by scripts/generate-engine-presets.py; do not edit by hand. */",
        "#ifndef FM1LAB_ENGINE_PRESETS_GENERATED_H",
        "#define FM1LAB_ENGINE_PRESETS_GENERATED_H", ""
    ]
    for engine in ENGINES:
        lines.append(f"static const engine_preset_t {engine}_presets[4] = {{")
        for patch_id, name, values in catalogs[engine]:
            nums = ", ".join(str(v) for v in values)
            safe_name = name.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    {{{{{nums}}}, "{safe_name}", "{patch_id}"}},')
        lines.extend(["};", f"#define FM1LAB_{engine.upper()}_PRESET_COUNT 4u", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(load_catalogs())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 scripts/generate-engine-presets.py")
        print("Native engine preset tables: catalog parity PASS")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"Generated {OUTPUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
